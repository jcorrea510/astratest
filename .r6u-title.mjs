import { chromium } from '@playwright/test';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
p.on('pageerror', e => console.log('ERR', e.message));
await p.goto('http://localhost:5210/astratest/');
await p.waitForFunction(() => window.__title, null, { timeout: 240000 });
await p.evaluate(() => { const g = window.__title.game; g.stop?.(); });
await p.evaluate(() => { const g = window.__title.game; for (let i=0;i<3;i++) g.frame(1/30, true); });
await p.waitForTimeout(500);
await p.screenshot({ path: '/tmp/claude-0/shots/u-title0.png', timeout: 240000 });
await p.keyboard.press('Space');
await p.waitForTimeout(1200);
await p.screenshot({ path: '/tmp/claude-0/shots/u-title1.png', timeout: 240000 });
await b.close();
