await p.evaluate(() => { const g = window.__game, a = window.__meridian.activities; g.money = 60000; a.buyCar('coupe'); a.checkMilestones(); a.openShop('dealer'); window.__game.frame(0.05,true); });
await p.waitForTimeout(4000);
await p.screenshot({ timeout: 180000, path: out + 'r6m-dealer.png' });
await p.evaluate(() => window.__meridian.activities.closeShop()); await p.waitForTimeout(500);
await p.evaluate(() => window.__meridian.ui.setPaused(true));
await p.waitForTimeout(1000);
await p.screenshot({ timeout: 180000, path: out + 'r6m-pause.png' });
await p.getByRole('tab',{name:'Goals'}).click({ force: true, timeout: 180000 }); await p.waitForTimeout(1000);
await p.screenshot({ timeout: 180000, path: out + 'r6m-goals.png' });
