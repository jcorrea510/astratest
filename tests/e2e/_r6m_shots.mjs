import { chromium } from '@playwright/test';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const out = '/tmp/claude-0/shots/';
await p.goto('http://127.0.0.1:5206/astratest/');
await p.waitForFunction(() => !!window.__title, null, { timeout: 240000 });
await p.keyboard.press('Space'); await p.waitForTimeout(1500);
await p.screenshot({ timeout: 180000, path: out + 'r6m-title.png' });
await p.getByRole('button', { name: 'New game' }).click({ force: true, timeout: 180000 }); await p.waitForTimeout(1000);
await p.screenshot({ timeout: 180000, path: out + 'r6m-picker.png' });
await p.getByRole('button', { name: 'Regular' }).click({ force: true, timeout: 180000 });
await p.waitForFunction(() => !!window.__meridian?.activities, null, { timeout: 240000 });
